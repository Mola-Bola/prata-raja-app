#!/usr/bin/env node
import { DatabaseSync } from 'node:sqlite';
import { execFileSync, spawn } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync, renameSync } from 'node:fs';
import { dirname, join, resolve, isAbsolute } from 'node:path';
import { fileURLToPath } from 'node:url';

const states = ['open', 'claimed', 'building', 'ready', 'failed', 'shipped', 'verified', 'dropped'];
const held = new Set(['claimed', 'building', 'ready', 'failed']);
const git = (cwd, args) => execFileSync('git', args, { cwd, encoding: 'utf8' }).trim();
export function commonRoot(cwd) {
  return dirname(git(cwd, ['rev-parse', '--path-format=absolute', '--git-common-dir']));
}
function paths(values) {
  if (!Array.isArray(values) || !values.length) throw new Error('owned must contain explicit relative paths');
  return [...new Set(values.map(p => {
    if (typeof p !== 'string' || !p || isAbsolute(p) || p.includes('\\') || p.split('/').some(x => x === '..' || x === '.') || /[*?\[\]\n\r]/.test(p)) throw new Error(`Invalid owned path: ${p}`);
    return p.replace(/\/+$/, '');
  }))];
}
export const overlaps = (a, b) => a.some(x => b.some(y => x === y || x.startsWith(`${y}/`) || y.startsWith(`${x}/`)));
const decode = r => r && ({ ...r, owned: JSON.parse(r.owned), dependsOn: JSON.parse(r.depends_on), decisions: JSON.parse(r.decisions), result: JSON.parse(r.result) });

export function openLedger(cwd = process.cwd(), { render: renderOnChange = true } = {}) {
  const root = commonRoot(cwd);
  const dir = join(root, '.fleet');
  mkdirSync(dir, { recursive: true });
  const db = new DatabaseSync(join(dir, 'ledger.db'));
  db.exec(`PRAGMA busy_timeout=10000; PRAGMA journal_mode=WAL;
    CREATE TABLE IF NOT EXISTS tasks (
      id INTEGER PRIMARY KEY, source TEXT NOT NULL, intent TEXT NOT NULL, brief TEXT NOT NULL,
      owned TEXT NOT NULL, depends_on TEXT NOT NULL, priority INTEGER NOT NULL DEFAULT 0,
      status TEXT NOT NULL DEFAULT 'open', worker TEXT, branch TEXT, release TEXT,
      decisions TEXT NOT NULL DEFAULT '[]', result TEXT NOT NULL DEFAULT 'null',
      created TEXT NOT NULL, updated TEXT NOT NULL);`);
  const list = () => db.prepare('SELECT * FROM tasks ORDER BY priority DESC, id').all().map(decode);
  const get = id => decode(db.prepare('SELECT * FROM tasks WHERE id=?').get(Number(id)));
  const cell = x => String(x ?? '').replace(/\|/g, '\\|').replace(/[\r\n]+/g, ' ');
  function render() {
    mkdirSync(join(root, 'docs'), { recursive: true });
    const output = ['# Fleet ledger', '', 'Generated by `node scripts/fleet.mjs`; SQLite in the common Git root is authoritative.', '', '| ID | Intent / source / dependencies | Status | Ownership | Worker / branch | Release | Decisions / result |', '| --- | --- | --- | --- | --- | --- | --- |',
      ...list().map(r => `| ${r.id} | ${cell(`${r.intent} — ${r.source}; depends: ${r.dependsOn.join(', ') || 'none'}`)} | ${r.status} | ${cell(r.owned.join(', '))} | ${cell([r.worker, r.branch].filter(Boolean).join(' / '))} | ${cell(r.release)} | ${cell([...r.decisions.map(d => d.note), r.result ? JSON.stringify(r.result) : ''].filter(Boolean).join('; '))} |`), ''].join('\n');
    const temp = join(root, 'docs', `.LEDGER-${process.pid}.tmp`);
    writeFileSync(temp, output);
    renameSync(temp, join(root, 'docs/LEDGER.md'));
  }
  function transaction(fn) {
    db.exec('BEGIN IMMEDIATE');
    try { const value = fn(); if (renderOnChange) render(); db.exec('COMMIT'); return value; }
    catch (error) { db.exec('ROLLBACK'); throw error; }
  }
  function add(task) {
    for (const key of ['source', 'intent', 'brief']) if (typeof task[key] !== 'string' || !task[key].trim()) throw new Error(`${key} is required`);
    const owned = paths(task.owned);
    const deps = task.dependsOn ?? [];
    if (!Array.isArray(deps) || !deps.every(x => Number.isSafeInteger(x) && x > 0)) throw new Error('Invalid dependsOn');
    const priority = task.priority ?? 0;
    if (!Number.isSafeInteger(priority)) throw new Error('Invalid priority');
    return transaction(() => {
      if (deps.some(id => !get(id))) throw new Error('Unknown dependency');
      const now = new Date().toISOString();
      const decisions = task.decision ? [{ at: now, note: String(task.decision) }] : [];
      const result = db.prepare('INSERT INTO tasks(source,intent,brief,owned,depends_on,priority,decisions,created,updated) VALUES(?,?,?,?,?,?,?,?,?)').run(task.source, task.intent, task.brief, JSON.stringify(owned), JSON.stringify(deps), priority, JSON.stringify(decisions), now, now);
      return get(result.lastInsertRowid);
    });
  }
  function claim(worker, id) {
    if (typeof worker !== 'string' || !worker.trim()) throw new Error('worker is required');
    return transaction(() => {
      const rows = list();
      const row = rows.find(r => r.status === 'open' && (id === undefined || r.id === Number(id)) &&
        r.dependsOn.every(dep => ['shipped', 'verified'].includes(get(dep)?.status)) &&
        !rows.some(other => held.has(other.status) && overlaps(r.owned, other.owned)));
      if (!row) return null;
      db.prepare("UPDATE tasks SET status='claimed',worker=?,updated=? WHERE id=?").run(worker, new Date().toISOString(), row.id);
      return get(row.id);
    });
  }
  function status(id, next, { note, branch, release, result } = {}) {
    if (!states.includes(next)) throw new Error('Invalid status');
    return transaction(() => {
      const row = get(id);
      if (!row) throw new Error('Unknown task');
      if (['claimed', 'building', 'ready'].includes(next) && !held.has(row.status)) throw new Error('Claim the task first');
      if (['verified', 'dropped'].includes(row.status) && next !== row.status) throw new Error('Terminal task: add a new row with a decision');
      if (next === 'open' && !note) throw new Error('Reopening requires a decision note');
      const now = new Date().toISOString();
      if (note) row.decisions.push({ at: now, note: String(note) });
      db.prepare('UPDATE tasks SET status=?,decisions=?,branch=?,release=?,result=?,updated=? WHERE id=?').run(next, JSON.stringify(row.decisions), branch ?? row.branch, release ?? row.release, JSON.stringify(result === undefined ? row.result : result), now, row.id);
      return get(row.id);
    });
  }
  return { root, dir, add, list, claim, status, render: () => transaction(() => { render(); return null; }), close: () => db.close() };
}

export function validateResult(cwd, row, name, reportPath = `/private/tmp/claude-501/slices/${name}/result.json`) {
  const report = JSON.parse(readFileSync(reportPath, 'utf8'));
  const expectedCwd = join(dirname(resolve(cwd)), `prata-raja-${name}`);
  if (!report.ok || report.name !== name || report.branch !== `sol/${name}` || report.cwd !== expectedCwd ||
      !/^[a-f0-9]{40}$/.test(report.base ?? '') || !/^[a-f0-9]{40}$/.test(report.head ?? '') ||
      git(expectedCwd, ['rev-parse', 'HEAD']) !== report.head || git(cwd, ['rev-parse', report.branch]) !== report.head) throw new Error('Missing, failed or stale pinned slice result');
  git(cwd, ['merge-base', '--is-ancestor', report.base, report.head]);
  const changed = git(cwd, ['diff', '--no-renames', '--name-only', '-z', report.base, report.head]).split('\0').filter(Boolean);
  const outside = changed.filter(p => !row.owned.some(area => p === area || p.startsWith(`${area}/`)));
  if (outside.length) throw new Error(`Slice changed unowned paths: ${outside.join(', ')}`);
  return { report: reportPath, base: report.base, head: report.head, changed };
}

export async function workers(cwd, { count = 3, maxTasks = 10, timeoutMs = 3600000, dryRun = false } = {}) {
  if (![count, maxTasks, timeoutMs].every(Number.isSafeInteger) || count < 1 || count > 4 || maxTasks < 1 || timeoutMs < 1) throw new Error('Invalid worker bounds');
  const ledger = openLedger(cwd);
  // Dry runs are previews: they never acquire claims or change existing task status.
  if (dryRun) { const plan = ledger.list().filter(r => r.status === 'open').map(r => ({ id: r.id, owned: r.owned, command: ['bash', 'scripts/slice.sh', `fleet-${r.id}`, '<generated brief>', '--dry-run'] })); ledger.close(); return plan; }
  try {
    const settled = await Promise.allSettled(Array.from({ length: count }, async (_, slot) => {
      const completed = [];
      for (let n = 0; n < maxTasks; n++) {
        const row = ledger.claim(`worker-${process.pid}-${slot}`);
        if (!row) break;
        const name = `fleet-${row.id}-${Date.now()}-${process.pid}`;
        const brief = join(ledger.dir, `${name}.md`);
        // ID-derived ports remain distinct across concurrent controllers, not just loop slots.
        const port = 10000 + row.id;
        if (port > 65535) { ledger.status(row.id, 'failed', { note: 'Task ID exceeds available worker port range' }); break; }
        writeFileSync(brief, `${row.brief}\n\nOwned paths only: ${row.owned.join(', ')}.\nNever merge or ship. Source: ${row.source}.\nBefore editing, write .fleet/claim.json with id ${row.id}, owned paths and intent.\n`);
        ledger.status(row.id, 'building', { branch: `sol/${name}` });
        const outcome = await new Promise(resolveResult => {
          const child = spawn('bash', [join(cwd, 'scripts/slice.sh'), name, brief], { cwd, detached: true, stdio: 'inherit', env: { ...process.env, PORT: String(port) } });
          let timedOut = false;
          const timer = setTimeout(() => { timedOut = true; try { process.kill(-child.pid, 'SIGKILL'); } catch {} }, timeoutMs);
          child.once('error', error => { clearTimeout(timer); resolveResult({ code: null, error: error.message }); });
          child.once('exit', (code, signal) => { clearTimeout(timer); resolveResult({ code, signal, timedOut }); });
        });
        if (outcome.code === 0) {
          try { Object.assign(outcome, validateResult(cwd, row, name)); }
          catch (error) { outcome.code = 1; outcome.error = error.message; }
        }
        ledger.status(row.id, outcome.code === 0 ? 'ready' : 'failed', { result: outcome, note: `Slice ${name}; lead must inspect pipeline report before integration` });
        completed.push({ id: row.id, ...outcome });
        if (outcome.code !== 0) break;
      }
      return completed;
    }));
    return settled.map(r => r.status === 'fulfilled' ? r.value : { error: r.reason.message });
  } finally { ledger.close(); }
}

async function main() {
  const [command, ...args] = process.argv.slice(2);
  if (command === 'workers') return workers(process.cwd(), { count: Number(args[0] ?? 3), dryRun: args.includes('--dry-run') });
  const ledger = openLedger();
  try {
    if (command === 'triage') {
      const row = ledger.list().find(r => r.id === Number(args[0]));
      if (!row) throw new Error('Unknown task');
      const { judge } = await import('./jev.mjs');
      const advisory = await judge({ task: 'overlap', text: row.intent, candidates: ledger.list().filter(r => r.id !== row.id && held.has(r.status)).map(r => ({ id: String(r.id), text: `${r.intent}; owned: ${r.owned.join(', ')}` })) });
      ledger.status(row.id, row.status, { note: `Jev advisory (lead decides): ${JSON.stringify(advisory)}` });
      return advisory;
    }
    if (command === 'add') return ledger.add(JSON.parse(readFileSync(args[0], 'utf8')));
    if (command === 'list') return ledger.list();
    if (command === 'claim') return ledger.claim(args[0], args[1]);
    if (command === 'status') return ledger.status(args[0], args[1], { note: args.slice(2).join(' ') || undefined });
    if (command === 'render') return ledger.render();
    throw new Error('Usage: fleet.mjs triage id | add task.json | list | claim worker [id] | status id state [note] | render | workers [1-4] [--dry-run]');
  } finally { ledger.close(); }
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main().then(value => console.log(JSON.stringify(value, null, 2))).catch(error => { console.error(error.message); process.exitCode = 1; });
