// The game overlay's design tokens (src/game/ui/*.css) in one place. Colours come from brand.game; the rest is the type scale,
// radii, spacing and motion of docs/wiki/ui-system.md. `gameTokenCss()` renders them as CSS custom properties on `.gu-root`
// into src/game/ui/tokens.css (regenerate: `UPDATE_TOKENS=1 npx vitest run src/ui/__tests__/gameTokens.test.ts`); the test
// fails when the file drifts, and checks every text/background pair for contrast.
import { brand } from './brand';

export const gameColors = brand.game;

const HEAD = 'Fredoka, system-ui, sans-serif';
const BODY = 'Nunito, system-ui, sans-serif';

/** Exactly five sizes. Nothing below 13. `font` is the CSS shorthand the classes use. */
export const TYPE = {
  hero: { px: 30, font: `700 30px/1.1 ${HEAD}` },
  title: { px: 22, font: `600 22px/1.15 ${HEAD}` },
  btn: { px: 18, font: `600 18px/1.1 ${HEAD}` },
  body: { px: 15, font: `700 15px/1.35 ${BODY}` },
  cap: { px: 13, font: `700 13px/1.3 ${BODY}` },
} as const;

/** Three radii: small cards and tiles, buttons and sheets, full (pills and circles). */
export const RADII = { s: '12px', m: '18px', full: '999px' } as const;
export const SPACE = [4, 8, 12, 16, 24] as const;
export const MOTION = { press: '90ms', in: '220ms', out: '140ms', ease: 'cubic-bezier(0.2, 0.8, 0.2, 1)' } as const;
/** Smallest tap target (px). */
export const TOUCH = 44;

const hexToRgb = (h: string) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16));

/** Every [text, background] pair the game draws, with the ratio it must reach (4.5 body and caption, 3 for t-btn and up). */
export const GAME_PAIRS: { name: string; fg: string; bg: string; min: number }[] = (() => {
  const c = gameColors;
  const [r, g, b] = hexToRgb(c.glass);
  const over = (base: number) => '#' + [r, g, b].map((v) => Math.round(v * c.glassAlpha + base * (1 - c.glassAlpha)).toString(16).padStart(2, '0')).join('');
  return [
    { name: 'ink on cream (panels, plain)', fg: c.ink, bg: c.cream, min: 4.5 },
    { name: 'ink on orange (go, selected chip, Dodge)', fg: c.ink, bg: c.orange, min: 4.5 },
    { name: 'ink on gold (tips, points)', fg: c.ink, bg: c.gold, min: 4.5 },
    { name: 'muted on cream (secondary text)', fg: c.muted, bg: c.cream, min: 4.5 },
    { name: 'muted on gold', fg: c.muted, bg: c.gold, min: 4.5 },
    { name: 'edge-deep on cream (cost, spent)', fg: c.edgeDeep, bg: c.cream, min: 4.5 },
    { name: 'edge-deep on gold (cost pill)', fg: c.edgeDeep, bg: c.gold, min: 4.5 },
    { name: 'red text on cream (needs, errors)', fg: c.redText, bg: c.cream, min: 4.5 },
    { name: 'cream on ink (toast, badge)', fg: c.cream, bg: c.ink, min: 4.5 },
    // The glass pill sits on art: its worst case is over white, and over black it only gets darker.
    { name: 'cream on glass over white (HUD pills)', fg: c.cream, bg: over(255), min: 4.5 },
  ];
})();

/** The text of src/game/ui/tokens.css. */
export function gameTokenCss(): string {
  const c = gameColors;
  const line = (k: string, v: string | number) => `  --${k}: ${v};`;
  const out: string[] = [
    '/* GENERATED by src/ui/gameTokens.ts (colours from brand.game). Do not edit; see docs/wiki/ui-system.md. */',
    '.gu-root {',
    ...Object.entries({ cream: c.cream, ink: c.ink, muted: c.muted, orange: c.orange, 'orange-deep': c.orangeDeep, red: c.red, 'red-text': c.redText, edge: c.edge, 'edge-deep': c.edgeDeep, gold: c.gold, 'glass-edge': c.glassEdge }).map(([k, v]) => line(k, v)),
    line('glass', `rgba(${hexToRgb(c.glass).join(', ')}, ${c.glassAlpha})`),
    ...Object.entries(TYPE).flatMap(([k, t]) => [line(`t-${k}`, `${t.px}px`), line(`f-${k}`, t.font)]),
    ...Object.entries(RADII).map(([k, v]) => line(`r-${k}`, v)),
    ...SPACE.map((v, i) => line(`sp-${i + 1}`, `${v}px`)),
    line('touch', `${TOUCH}px`),
    line('m-press', MOTION.press),
    line('m-in', MOTION.in),
    line('m-out', MOTION.out),
    line('m-ease', MOTION.ease),
    '}',
    '',
  ];
  return out.join('\n');
}
